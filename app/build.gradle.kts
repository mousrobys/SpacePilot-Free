val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) {
        file.inputStream().use { load(it) }
    }
}

fun signingValue(property: String, key: String): String? =
    providers.gradleProperty(property).orNull?.takeIf { it.isNotBlank() }
        ?: keystoreProperties.getProperty(key)?.takeIf { it.isNotBlank() }

val releaseKeystorePath = signingValue("SPACEPILOT_KEYSTORE", "SPACEPILOT_KEYSTORE")
val releaseKeystorePassword = signingValue("SPACEPILOT_KEYSTORE_PASSWORD", "SPACEPILOT_KEYSTORE_PASSWORD")
val releaseKeyAlias = signingValue("SPACEPILOT_KEY_ALIAS", "SPACEPILOT_KEY_ALIAS")
val releaseKeyPassword = signingValue("SPACEPILOT_KEY_PASSWORD", "SPACEPILOT_KEY_PASSWORD")
val hasReleaseSigning = listOf(
    releaseKeystorePath,
    releaseKeystorePassword,
    releaseKeyAlias,
    releaseKeyPassword
).all { !it.isNullOrBlank() }

